#!/usr/bin/env node
/* Builds css/app.css, the single stylesheet index.html loads.
   The source files stay in css/ and are concatenated in this exact order
   (later files override earlier ones, as when they were 24 separate links).
   Run: node tools/build-css.js        -> writes css/app.css
        node tools/build-css.js --check -> fails if css/app.css is stale */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const SOURCES = [
  'css/style.css',
  'css/cosmic.css',
  'css/cosmic-design.css',
  'css/cosmic-controls.css',
  'css/cosmic-fidelity.css',
  'css/cosmic-v4.css',
  'css/cosmic-v5.css',
  'css/cosmic-v6.css',
  'css/cosmic-v7.css',
  'css/cosmic-v8.css',
  'css/cosmic-v9.css',
  'css/cosmic-v10.css',
  'css/cosmic-lite.css',
  'css/cosmic-layout-v12.css',
  'css/cosmic-reflections-v13.css',
  'css/premium-controls-v14.css',
  'css/dark-frosted-glass-v15.css',
  'css/clear-glass-v16.css',
  'css/liquid-glass-v17.css',
  'css/course-lightglass-v18.css',
  'css/unified-glass-sky-drift-v19.css',
  'css/sky-motion-v21.css',
  'css/sky-motion-v23.css',
  'css/sky-speed-settings-v24.css',
  'css/premium-motion-v25.css',
  'css/space-v27.css',
  'css/refine-v28.css'
];
const out = SOURCES.map(file => '/* @source ./' + file + ' */\n' + fs.readFileSync(path.join(root, file), 'utf8').trim() + '\n').join('\n');
const target = path.join(root, 'css', 'app.css');
const header = '/* GENERATED by tools/build-css.js from ' + SOURCES.length + ' files. Edit the sources, then rebuild. */\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== header + out) { console.error('css/app.css is out of date: run node tools/build-css.js'); process.exit(1); }
  console.log('css/app.css is up to date');
} else {
  fs.writeFileSync(target, header + out);
  console.log('Wrote css/app.css from ' + SOURCES.length + ' files');
}
